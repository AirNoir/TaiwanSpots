#!/usr/bin/env node
// Scans assets/spots/<id>/{collection,world}/ and writes the static require()
// map Metro needs (src/data/spotAssets.generated.ts). Run after adding or
// replacing any spot image:  npm run assets:registry
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pickRuntimeImage as pick } from './spot-asset-files.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spotsDir = join(root, 'assets/spots');
const outFile = join(root, 'src/data/spotAssets.generated.ts');

const IMAGE = /\.(png|webp|jpe?g|avif)$/i;
const COLLECTION_VARIANTS = ['day', 'sunset', 'night', 'thumbnail'];

function firstImage(dir) {
  if (!existsSync(dir)) return null;
  return readdirSync(dir).filter((f) => IMAGE.test(f)).sort()[0] ?? null;
}

const ids = readdirSync(spotsDir)
  .filter((d) => statSync(join(spotsDir, d)).isDirectory())
  .sort();

const lines = [];
for (const id of ids) {
  const entries = [];
  const collectionDir = join(spotsDir, id, 'collection');
  const variants = COLLECTION_VARIANTS.map((v) => [v, pick(collectionDir, v)]).filter(([, f]) => f);
  if (variants.length) {
    const body = variants
      .map(([v, f]) => `      ${v}: require('../../assets/spots/${id}/collection/${f}'),`)
      .join('\n');
    entries.push(`    collection: {\n${body}\n    },`);
  }
  const worldDir = join(spotsDir, id, 'world');
  const token = pick(worldDir, 'landmark') ?? firstImage(worldDir);
  if (token) entries.push(`    world: require('../../assets/spots/${id}/world/${token}'),`);
  if (entries.length) lines.push(`  '${id}': {\n${entries.join('\n')}\n  },`);
}

const out = `// AUTO-GENERATED by scripts/generate-asset-registry.mjs — do not edit by hand.
import type { SpotAssetSet } from './spotAssets';

export const GENERATED_SPOT_ASSETS: Record<string, SpotAssetSet> = {
${lines.join('\n')}
};
`;
writeFileSync(outFile, out);
console.log(`wrote ${outFile} (${lines.length} spots)`);
